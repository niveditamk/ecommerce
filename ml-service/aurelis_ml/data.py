"""Read-only access to the Aurelis database.

Node owns this file. Python opens it through a mode=ro URI so that a bug,
a stray commit or an experiment in a notebook cannot corrupt the shop's
own data — two processes writing one SQLite file is exactly the failure
this architecture exists to avoid.

The series produced here has to match server/src/ml/forecast.js day for
day. Python versions land on the same leaderboard as the Node baselines
and are judged by the same metrics, so a difference of one censored day
would not show up as a bug: it would show up as Python winning.
"""

from __future__ import annotations

import sqlite3
from collections.abc import Iterator, Sequence
from contextlib import contextmanager
from dataclasses import dataclass
from datetime import date, timedelta
from pathlib import Path
from typing import Any, Final

from .config import ON_HAND_TYPES, ConfigError, db_uri, require_db

__all__ = [
    "Point",
    "DemandSeries",
    "connect",
    "active_products",
    "demand_series",
    "rfm_rows",
    "synthetic_stats",
]

# Orders generated by server/src/ml/synthetic.js carry this channel. Every
# synthetic row is labelled at source, so anything reporting on real trade
# filters on it rather than trying to guess which sales were invented.
SYNTHETIC_CHANNEL: Final[str] = "synthetic"

# Built once: the IN (...) list has to bind ON_HAND_TYPES as parameters,
# never interpolate them, even though they are constants today.
_ON_HAND_PLACEHOLDERS: Final[str] = ",".join("?" for _ in ON_HAND_TYPES)


# ---------------------------------------------------------------------
# Connection
# ---------------------------------------------------------------------
@contextmanager
def connect(path: Path | str | None = None) -> Iterator[sqlite3.Connection]:
    """Yield a read-only connection, closed on the way out.

    PRAGMA query_only is set on top of mode=ro as belt and braces: the URI
    already denies writes at the file level, and this denies them at the
    statement level, so a stray INSERT fails with a message about being
    read-only rather than about a locked file.

    The database runs in WAL mode, which is why the reader never blocks
    the shop: Node can accept orders throughout a training run.
    """
    target = require_db(path)
    try:
        conn = sqlite3.connect(db_uri(target), uri=True)
    except sqlite3.OperationalError as exc:
        raise ConfigError(
            f"Could not open {target} read-only: {exc}. If the server is mid-write, "
            "the -wal and -shm files beside it must be readable too."
        ) from exc

    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA query_only = TRUE")
    try:
        yield conn
    finally:
        conn.close()


@contextmanager
def _using(conn: sqlite3.Connection | None) -> Iterator[sqlite3.Connection]:
    """Reuse a caller's connection, or open one for the duration.

    Training walks every SKU in turn; reopening the file per SKU would
    re-read the WAL index each time for no benefit. Callers that have a
    connection pass it down, callers that do not are not made to care.
    """
    if conn is not None:
        yield conn
        return
    with connect() as fresh:
        yield fresh


def _rows(conn: sqlite3.Connection, sql: str, params: Sequence[Any] = ()) -> list[dict[str, Any]]:
    """Run a query and detach the results from the cursor.

    sqlite3.Row is convenient but keeps callers tied to the database
    layer; plain dicts serialise straight into the payload posted to Node.
    """
    return [dict(row) for row in conn.execute(sql, tuple(params)).fetchall()]


# ---------------------------------------------------------------------
# Series types
# ---------------------------------------------------------------------
@dataclass(frozen=True, slots=True)
class Point:
    """One calendar day of demand for one SKU.

    `censored` does not mean "no data". It means the shelf was empty, so
    the zero recorded that day is evidence of nothing at all and must be
    kept out of both fitting and scoring.
    """

    day: str        # YYYY-MM-DD
    units: int
    censored: bool


@dataclass(frozen=True, slots=True)
class DemandSeries:
    """A SKU's full daily history, zero-filled across the calendar.

    Gaps are filled because a day with no order row is a real zero — a day
    nobody bought — and dropping it would quietly shorten the series and
    inflate the average.
    """

    sku: str
    points: list[Point]
    censored: int

    @property
    def usable(self) -> list[Point]:
        """The days a model is allowed to learn from and be scored on."""
        return [p for p in self.points if not p.censored]

    @property
    def first_day(self) -> str | None:
        """First calendar day, for ml_versions.train_from."""
        return self.points[0].day if self.points else None

    @property
    def last_day(self) -> str | None:
        """Last calendar day, for ml_versions.train_to."""
        return self.points[-1].day if self.points else None


# ---------------------------------------------------------------------
# Calendar and censoring
# ---------------------------------------------------------------------
def _each_day(start: str, end: str) -> list[str]:
    """Every ISO day from start to end inclusive."""
    first = date.fromisoformat(start)
    last = date.fromisoformat(end)
    out: list[str] = []
    step = first
    while step <= last:
        out.append(step.isoformat())
        step += timedelta(days=1)
    return out


def _censored_days(conn: sqlite3.Connection, sku: str, calendar: Sequence[str]) -> set[str]:
    """Days on which the SKU was unavailable to sell.

    Stock is a STATE, not an event. A piece that runs out on Monday and is
    restocked on Friday writes no ledger row on Tuesday, Wednesday or
    Thursday — and those silent days are exactly the ones that matter
    most, because they are where the zeros come from. The balance is
    therefore carried forward across quiet days rather than read as a
    sequence of events.

    Only ON_HAND_TYPES are consulted: reservation movements write the
    reserved count into the same new_qty column, and an expiring
    reservation dropping reserved to 0 looks exactly like an empty shelf.
    """
    rows = conn.execute(
        f"""
        SELECT substr(created_at,1,10) AS day, MIN(new_qty) AS low, MAX(new_qty) AS high
          FROM inventory_transactions
         WHERE product_id = ? AND new_qty IS NOT NULL
           AND type IN ({_ON_HAND_PLACEHOLDERS})
         GROUP BY day ORDER BY day ASC
        """,
        (sku, *ON_HAND_TYPES),
    ).fetchall()

    by_day: dict[str, sqlite3.Row] = {row["day"]: row for row in rows}
    blocked: set[str] = set()

    # Unknown until the ledger first says something. Days before the first
    # movement are left uncensored rather than guessed at — refusing to
    # invent a stock level is the same rule as refusing to invent a
    # forecast.
    carried: int | None = None

    for day in calendar:
        today = by_day.get(day)
        if today is not None:
            # Out for part of the day still means demand was suppressed,
            # so the low water mark decides, not the closing balance.
            if today["low"] <= 0:
                blocked.add(day)
            carried = today["high"]
            continue
        if carried is not None and carried <= 0:
            blocked.add(day)

    return blocked


