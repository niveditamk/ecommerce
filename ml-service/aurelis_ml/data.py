def active_products(conn: sqlite3.Connection | None = None) -> list[dict[str, Any]]:
    """The catalogue worth modelling.

    Draft and archived pieces are excluded: a forecast for something that
    cannot be bought is a number nobody can act on.
    """
    with _using(conn) as db:
        return _rows(
            db,
            """
            SELECT id, name, price, stock, reserved, incoming, safety_stock
              FROM products
             WHERE status = 'active'
             ORDER BY name
            """,
        )


def demand_series(
    sku: str,
    *,
    start: str | None = None,
    end: str | None = None,
    conn: sqlite3.Connection | None = None,
) -> DemandSeries:
    """Daily units sold for one SKU, zero-filled and censored.

    The window is bounded by the SKU's own first and last order rather
    than by the shop's trading history: padding a piece launched in June
    back to March would fabricate months of zero demand for something that
    was not on sale.

    Cancelled orders are excluded because a cancellation is not a sale;
    synthetic orders are NOT, because synthetic history exists precisely
    so there is something to train on, and it is labelled at source.
    """
    with _using(conn) as db:
        bounds = db.execute(
            """
            SELECT MIN(substr(o.placed_at,1,10)) AS a, MAX(substr(o.placed_at,1,10)) AS b
              FROM order_items i JOIN orders o ON o.id = i.order_id
             WHERE i.product_id = ? AND o.status != 'Cancelled'
            """,
            (sku,),
        ).fetchone()

        first = start or (bounds["a"] if bounds else None)
        last = end or (bounds["b"] if bounds else None)
        if not first or not last:
            # Never sold. An empty series is the honest answer; a series of
            # zeros would read as measured indifference.
            return DemandSeries(sku=sku, points=[], censored=0)

        sold = {
            row["day"]: int(row["units"])
            for row in db.execute(
                """
                SELECT substr(o.placed_at,1,10) AS day, SUM(i.qty) AS units
                  FROM order_items i JOIN orders o ON o.id = i.order_id
                 WHERE i.product_id = ? AND o.status != 'Cancelled'
                   AND substr(o.placed_at,1,10) BETWEEN ? AND ?
                 GROUP BY day
                """,
                (sku, first, last),
            ).fetchall()
        }

        calendar = _each_day(first, last)
        blocked = _censored_days(db, sku, calendar)

    points: list[Point] = []
    for day in calendar:
        units = sold.get(day, 0)
        # A day with sales is never censored however the ledger read: the
        # piece demonstrably sold, so the observation is real. Censoring
        # only ever removes an uninformative zero.
        points.append(Point(day=day, units=units, censored=day in blocked and units == 0))

    return DemandSeries(
        sku=sku,
        points=points,
        censored=sum(1 for p in points if p.censored),
    )


def rfm_rows(conn: sqlite3.Connection | None = None) -> list[dict[str, Any]]:
    """Recency, frequency and monetary value per customer, real orders only.

    Synthetic history carries no customer, deliberately. Segmenting on it
    would produce tidy five-tier output describing people who do not
    exist, which is worse than having no segmentation at all.

    recency_days is whole days since the last order, measured against
    julianday('now') so the arithmetic matches the Node implementation
    rather than drifting with the Python process's clock handling.
    """
    with _using(conn) as db:
        return _rows(
            db,
            f"""
            SELECT c.id, c.first_name || ' ' || c.last_name AS name, c.email,
                   COUNT(o.id) AS frequency,
                   COALESCE(SUM(o.total), 0) AS monetary,
                   MAX(o.placed_at) AS last_order,
                   CAST(julianday('now') - julianday(MAX(o.placed_at)) AS INTEGER) AS recency_days
              FROM customers c
              JOIN orders o ON o.customer_id = c.id
             WHERE o.status != 'Cancelled' AND o.channel != '{SYNTHETIC_CHANNEL}'
             GROUP BY c.id
             ORDER BY monetary DESC
            """,
        )


def synthetic_stats(conn: sqlite3.Connection | None = None) -> dict[str, Any]:
    """How much of the order history is invented, and over what period.

    Reported alongside every trained version so nobody reads a model built
    on generated demand as a statement about real trade. Keys mirror the
    Node syntheticStats() payload so the existing console renders it
    without change.
    """
    with _using(conn) as db:
        syn = db.execute(
            """
            SELECT COUNT(*) AS orders, MIN(substr(placed_at,1,10)) AS a,
                   MAX(substr(placed_at,1,10)) AS b
              FROM orders WHERE channel = ?
            """,
            (SYNTHETIC_CHANNEL,),
        ).fetchone()
        real = db.execute(
            """
            SELECT COUNT(*) AS orders, MIN(substr(placed_at,1,10)) AS a,
                   MAX(substr(placed_at,1,10)) AS b
              FROM orders WHERE channel != ?
            """,
            (SYNTHETIC_CHANNEL,),
        ).fetchone()

    synthetic_orders = int(syn["orders"])
    real_orders = int(real["orders"])
    total = synthetic_orders + real_orders

    return {
        "synthetic": {"orders": synthetic_orders, "from": syn["a"], "to": syn["b"]},
        "real": {"orders": real_orders, "from": real["a"], "to": real["b"]},
        # int(x + 0.5), not round(): Python rounds halves to even and
        # JavaScript rounds them up, and this figure is compared against
        # the Node-rendered one by eye in the console.
        "syntheticShare": int((synthetic_orders / total) * 100 + 0.5) if total else 0,
        "present": synthetic_orders > 0,
    }
